import { expect, test } from "@playwright/test";
import { mockCommerce } from "./commerce-fixture";

test("el mate se agrega con modelo, forma y cuero; el diseño y los materiales siguen editables", async ({ page }) => {
  await mockCommerce(page);
  await page.goto("/comercial/registrar-min");
  await page.getByRole("tab", { name: "Personalizados" }).click();
  await page.getByLabel("Categoría de artículo").selectOption("mate");
  const picker = page.locator(".local-custom-builder");
  const add = picker.getByRole("button", { name: "Agregar personalizado" });
  await picker.getByLabel("Modelo", { exact: true }).selectOption("criollo");
  await expect(picker.locator(".field-required")).toHaveCount(3);
  await expect(add).toBeDisabled();
  await picker.getByLabel("Forma del criollo").selectOption("torpedo");
  await expect(add).toBeDisabled();
  await picker.getByLabel("Cuero o textura").selectOption("liso");
  await expect(add).toBeEnabled();
  await expect(picker.getByLabel("Color")).toHaveCount(0);
  await expect(picker.getByLabel("Precio rápido del mate")).toContainText("1.300");
  await page.screenshot({ path: "artifacts/local-personalized-picker.png" });
  await add.click();
  await expect(page.getByRole("button", { name: "Guardar venta" })).toBeDisabled();
  await expect(page.locator(".local-sale-footer")).toContainText("Total estimado");
  await expect(page.getByLabel("Precio unitario de Mate Criollo personalizado")).toHaveValue(/1\.300/);

  const card = page.locator(".local-personalization-card").first();
  const steps = card.getByRole("navigation", { name: "Pasos del diseño de Mate Criollo personalizado" });
  await expect(steps.getByRole("button", { name: /Virola/ })).toHaveAttribute("aria-current", "step");
  await card.getByLabel("Texto de virola de Mate Criollo personalizado").fill("ENZO");
  await card.getByLabel("Texto 2 para la virola de Mate Criollo personalizado").fill("MATE");
  const rimPreview = card.getByLabel("Vista editable de la virola criollo");
  await rimPreview.locator('[data-rim-text-id="text-1"] path[stroke="transparent"]').click();
  await rimPreview.getByRole("button", { name: "Invertir el texto y ponerlo abajo" }).click();
  await expect(rimPreview.getByRole("button", { name: "Volver a poner el texto arriba" })).toBeVisible();
  await expect(rimPreview.locator('[data-rim-text-id="text-2"]')).toBeVisible();
  await rimPreview.screenshot({ path: "artifacts/local-personalized-two-rim-texts.png" });
  await page.getByRole("button", { name: "Editar diseño y materiales" }).click();
  await steps.getByRole("button", { name: /Materiales/ }).click();
  await card.getByLabel("Forma del criollo").selectOption("imperial");
  await card.getByLabel("Cuero o textura").selectOption("croco");
  await expect(card.getByLabel("Precio del armado")).toContainText("2.700");
  await expect(page.getByLabel("Precio unitario de Mate Criollo personalizado")).toHaveValue(/2\.820/);
  await expect(page.locator(".local-sale-lines").last()).toContainText("Forma del criollo: Imperial");
  await expect(page.locator(".local-sale-lines").last()).toContainText("Cuero o textura: Croco");
  await page.screenshot({ path: "artifacts/local-personalized-materials.png" });
  await steps.getByRole("button", { name: /Virola/ }).click();
  await expect(card.getByLabel("Texto de virola de Mate Criollo personalizado")).toHaveValue("ENZO");
  await expect(card.getByLabel("Texto 2 para la virola de Mate Criollo personalizado")).toHaveValue("MATE");
});
